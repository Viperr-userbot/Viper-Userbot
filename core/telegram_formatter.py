"""
core/telegram_formatter.py

High-reliability Telegram Markdown-to-HTML formatter and sanitizer.
Transforms standard LLM Markdown into clean, rich Telegram HTML (<b>bold</b>, <i>italic</i>, <code>code</code>)
while eliminating raw asterisks (**) and maintaining a 100% fail-safe fallback.
"""

import html
import re


def markdown_to_telegram_html(text: str) -> str:
    """
    Converts standard Markdown generated by LLMs to Telegram-supported HTML.
    Telegram HTML supports: <b>, <i>, <u>, <s>, <code>, <pre>, <blockquote>, <a href="...">.
    Safely escapes <, >, & in non-code text to prevent XML/HTML parsing errors.
    """
    if not text:
        return ""

    # 1. Protect code blocks (```lang\ncode\n```)
    code_blocks: list[str] = []

    def _save_code_block(match: re.Match) -> str:
        lang = (match.group(1) or "").strip()
        code = match.group(2)
        escaped_code = html.escape(code.strip("\r\n"))
        idx = len(code_blocks)
        if lang:
            code_blocks.append(f'<pre><code class="language-{html.escape(lang)}">{escaped_code}</code></pre>')
        else:
            code_blocks.append(f'<pre><code>{escaped_code}</code></pre>')
        return f"%%TGCB{idx}%%"

    text = re.sub(r'```([a-zA-Z0-9_\+\-]+)?\r?\n([\s\S]*?)```', _save_code_block, text)
    text = re.sub(r'```([a-zA-Z0-9_\+\-]+)?\s*([\s\S]*?)```', _save_code_block, text)

    # 2. Protect inline code (`code`)
    inline_codes: list[str] = []

    def _save_inline_code(match: re.Match) -> str:
        code = match.group(1)
        escaped = html.escape(code)
        idx = len(inline_codes)
        inline_codes.append(f'<code>{escaped}</code>')
        return f"%%TGIC{idx}%%"

    text = re.sub(r'`([^`\r\n]+)`', _save_inline_code, text)

    # 3. HTML escape remaining plain text (&, <, >)
    text = html.escape(text, quote=False)

    # 4. Horizontal rules (---, ***, ___)
    text = re.sub(r'^[ \t]*[-*_]{3,}[ \t]*$', '──────────────', text, flags=re.MULTILINE)

    # 5. Headers (# Heading ... ###### Heading) -> bold heading
    text = re.sub(r'^[ \t]*#{1,6}[ \t]+(.+)$', r'<b>\1</b>', text, flags=re.MULTILINE)

    # 6. Blockquotes (> quote)
    text = re.sub(r'^[ \t]*>[ \t]*(.+)$', r'<blockquote>\1</blockquote>', text, flags=re.MULTILINE)

    # 7. Bullet lists (* item, - item) -> • item
    text = re.sub(r'^[ \t]*[\*\-][ \t]+', '• ', text, flags=re.MULTILINE)

    # 8. Bold + Italic: ***text***
    text = re.sub(r'\*\*\*(.+?)\*\*\*', r'<b><i>\1</i></b>', text)

    # 9. Bold: **text**
    text = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', text)

    # 10. Bold: __text__ (bounded by non-alphanumeric)
    text = re.sub(r'(?<![a-zA-Z0-9])__(.+?)__(?![a-zA-Z0-9])', r'<b>\1</b>', text)

    # 11. Italic: *text* (avoid matching math like 2 * 3 = 6 or bullets)
    text = re.sub(r'(?<![a-zA-Z0-9\*])\*(?!\s)([^*\r\n]+?)(?<!\s)\*(?![a-zA-Z0-9\*])', r'<i>\1</i>', text)

    # 12. Italic: _text_ (avoid matching snake_case variables)
    text = re.sub(r'(?<![a-zA-Z0-9])_(?!\s)([^_\r\n]+?)(?<!\s)_(?![a-zA-Z0-9])', r'<i>\1</i>', text)

    # 13. Strikethrough: ~~text~~
    text = re.sub(r'~~(.+?)~~', r'<s>\1</s>', text)

    # 14. Markdown links: [text](http://...)
    text = re.sub(r'\[([^\]]+)\]\((https?://[^\s\)]+)\)', r'<a href="\2">\1</a>', text)

    # 15. Clean up any leftover unbalanced ** markers so raw ** never leaks
    text = text.replace('**', '')

    # 16. Restore inline codes
    for idx, snippet in enumerate(inline_codes):
        text = text.replace(f"%%TGIC{idx}%%", snippet)

    # 17. Restore code blocks
    for idx, snippet in enumerate(code_blocks):
        text = text.replace(f"%%TGCB{idx}%%", snippet)

    return text.strip()


def strip_markdown_markers(text: str) -> str:
    """
    Fallback cleaner: generates clean plain text by removing asterisks (**),
    hashes (#), and formatting noise without losing words.
    """
    if not text:
        return ""
    cleaned = re.sub(r'\*\*\*(.*?)\*\*\*', r'\1', text)
    cleaned = re.sub(r'\*\*(.*?)\*\*', r'\1', text)
    cleaned = re.sub(r'(?<![a-zA-Z0-9\*])\*(?!\s)([^*\r\n]+?)(?<!\s)\*(?![a-zA-Z0-9\*])', r'\1', cleaned)
    cleaned = cleaned.replace('**', '')
    cleaned = re.sub(r'^[ \t]*#{1,6}[ \t]+', '', cleaned, flags=re.MULTILINE)
    cleaned = re.sub(r'^[ \t]*[\*\-][ \t]+', '• ', cleaned, flags=re.MULTILINE)
    return cleaned.strip()


def split_text_cleanly(text: str, max_chunk: int = 3800) -> list[str]:
    """
    Splits long messages on paragraph or line boundaries to prevent cutting
    words or formatting tags mid-sentence.
    """
    if not text:
        return []
    if len(text) <= max_chunk:
        return [text]

    chunks: list[str] = []
    current: list[str] = []
    current_len = 0

    paragraphs = text.split("\n\n")
    for para in paragraphs:
        if current_len + len(para) + 2 <= max_chunk:
            current.append(para)
            current_len += len(para) + 2
        else:
            if current:
                chunks.append("\n\n".join(current))
                current = []
                current_len = 0

            # If a single paragraph is longer than max_chunk, split by lines
            if len(para) > max_chunk:
                lines = para.split("\n")
                for line in lines:
                    if current_len + len(line) + 1 <= max_chunk:
                        current.append(line)
                        current_len += len(line) + 1
                    else:
                        if current:
                            chunks.append("\n".join(current))
                            current = []
                            current_len = 0
                        # If a single line is still too long, hard-chunk it
                        while len(line) > max_chunk:
                            chunks.append(line[:max_chunk])
                            line = line[max_chunk:]
                        if line:
                            current.append(line)
                            current_len += len(line) + 1
            else:
                current.append(para)
                current_len += len(para) + 2

    if current:
        chunks.append("\n\n".join(current))

    return chunks


def prepare_telegram_chunks(text: str, max_chunk: int = 3800) -> list[tuple[str, str]]:
    """
    Returns a list of (html_chunk, plain_fallback_chunk) pairs for bulletproof sending.
    """
    raw_chunks = split_text_cleanly(text, max_chunk=max_chunk)
    result = []
    for chunk in raw_chunks:
        html_version = markdown_to_telegram_html(chunk)
        plain_version = strip_markdown_markers(chunk)
        result.append((html_version, plain_version))
    return result
